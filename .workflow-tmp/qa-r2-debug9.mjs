/* git 模块列表页 doc 卡片点击是否失效（与 /javascript/ 同类的 doc-list-link） */
import path from 'node:path';
import { createRequire } from 'node:module';
const ROOT = 'C:/Atian/Project/FANDEX';
const { chromium } = createRequire(path.join(ROOT, 'app-web/package.json'))('playwright');
const BASE = 'http://localhost:4321/FANDEX/';
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
page.on('pageerror', e => console.log('PAGEERROR', String(e).slice(0,200)));
await page.goto(BASE+'git/', { waitUntil: 'load' });
await page.waitForTimeout(1000);
const link = page.locator('a[href="/FANDEX/git/110-HEADPointerBranchEssence/"]').first();
console.log('count', await link.count());
const info = await link.evaluate(el => ({rect:(r=>({x:Math.round(r.x),y:Math.round(r.y),w:Math.round(r.width),h:Math.round(r.height)}))(el.getBoundingClientRect()), cls: el.className.slice(0,50)}));
console.log('info', JSON.stringify(info));
await link.scrollIntoViewIfNeeded().catch(()=>{});
await page.waitForTimeout(300);
await link.click({ timeout: 6000 }).catch(e => console.log('click err', String(e).slice(0, 120)));
await page.waitForTimeout(1200);
console.log('after click:', page.url());
await browser.close();
