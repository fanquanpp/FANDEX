import { createRequire } from 'node:module';
import path from 'node:path';
const { chromium } = createRequire('C:/Atian/Project/FANDEX/app-web/package.json')('playwright');
const browser = await chromium.launch({ headless: true, args: ['--disable-blink-features=AutomationControlled'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const stacks = [];
page.on('pageerror', (e) => stacks.push({ msg: e.message, stack: (e.stack||'').split('\n').slice(0, 6).join('\n') }));
page.on('response', (r) => { if (r.status() >= 400) stacks.push({ res404: r.status() + ' ' + r.url() }); });
await page.goto('http://localhost:4321/FANDEX/', { waitUntil: 'load' });
await page.waitForTimeout(1500);
console.log(JSON.stringify(stacks, null, 2).slice(0, 4000));
await browser.close();
