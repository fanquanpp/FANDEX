import { createRequire } from 'node:module';
const { chromium } = createRequire('C:/Atian/Project/FANDEX/app-web/package.json')('playwright');
const browser = await chromium.launch({ headless: true, args: ['--disable-blink-features=AutomationControlled'] });
const page = await browser.newPage({ viewport: { width: 375, height: 1700 } });
const errs = [];
page.on('pageerror', (e) => errs.push('PE ' + e.message.slice(0, 120)));
page.on('console', (m) => { if (m.type() === 'error') errs.push('CE ' + m.text().slice(0, 120)); });
await page.goto('http://localhost:4321/FANDEX/playground/', { waitUntil: 'load' });
await page.waitForTimeout(2000);
console.log('playground narrow errors:', errs.length ? errs : 'clean');
const themeBtn = await page.evaluate(() => !!document.querySelector('.fndx-theme-toggle'));
console.log('themeToggle mounted:', themeBtn);
await browser.close();
